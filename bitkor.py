def gradcam_isi_haritasi(img_array):
    with tf.GradientTape() as tape:
        tape.watch(base_model.input)
        konv_out, tahminler = grad_model(img_array)
        hedef_indeks = tf.argmax(tahminler[0])
        kayip = tahminler[:, hedef_indeks]

    gradyanlar = tape.gradient(kayip, konv_out)
    havuzlanmis_gradyanlar = tf.reduce_mean(gradyanlar, axis=(0, 1, 2))
    isi_haritasi = konv_out[0] @ havuzlanmis_gradyanlar[..., tf.newaxis]
    isi_haritasi = tf.squeeze(isi_haritasi)

    isi_haritasi = tf.maximum(isi_haritasi, 0) / (tf.math.reduce_max(isi_haritasi) + 1e-10)
    return isi_haritasi.numpy()

