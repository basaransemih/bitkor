def dinamik_anomali_analizi(gorsel, sulama_adedi, sicaklik, nem):
    if gorsel is None:
        return None, "Lütfen incelenecek yaprak/bitki fotoğrafını yükleyin.", grafik_yolu

    img_pil = Image.fromarray(gorsel).convert('RGB')
    w, h = img_pil.size
    img_np = np.array(img_pil).astype(np.float32)

    r = img_np[:, :, 0]
    g = img_np[:, :, 1]
    b = img_np[:, :, 2]

    # Sağlıklı Klorofil Baz Hattı (Homojen Yaprak İndeksi)
    # Sağlıklı yeşil dokuda G kanalı R ve B'den belirgin şekilde yüksektir
    klorofil_dengesi = (g - (r + b) / 2.0)
    saglikli_alan = klorofil_dengesi > 15

    # Dokusal Sapma Haritası (Anomali Matrisi):
    # Sağlıklı profilden sapan her türlü renk bozulması (solma, kuruma, leke, küf, yanık)
    sapma_matrisi = np.zeros((h, w), dtype=np.float32)

    # 1. Nekrotik / Koyu Bozulmalar (Çürüme, yanıklık, siyah leke)
    koyu_bozulma = (r < 75) & (g < 75) & (b < 75)
    # 2. Klorotik / Sarı-Kahve Kurumalar (Besin eksikliği, akar, güneş yanığı)
    sari_kuruma = (r > 120) & (g > 90) & (b < 100) & (r > g)
    # 3. Yüzeyel Unsu / Toz Mantar Bozulmaları (Külleme, pamuksu unlu bit)
    unsu_bozulma = (r > 175) & (g > 175) & (b > 175) & (abs(r - g) < 25)

    sapma_matrisi[koyu_bozulma] = 0.90
    sapma_matrisi[sari_kuruma] = 0.75
    sapma_matrisi[unsu_bozulma] = 0.85

    # Toplam deformasyon oranı
    hasarli_piksel_orani = np.mean(sapma_matrisi > 0)
    anomali_skoru = min(hasarli_piksel_orani * 320, 99.5)

    # Eğer dokuda anomali tespit edildiyse
    if hasarli_piksel_orani > 0.02:
        durum_basligi = "Doku Anomalisi ve Patolojik Bozulma Saptandı"

        # Hakim deformasyon türünü analiz et
        koyu_oran = np.sum(koyu_bozulma)
        sari_oran = np.sum(sari_kuruma)
        unsu_oran = np.sum(unsu_bozulma)

        baskin_hasar = max(koyu_oran, sari_oran, unsu_oran)
        if baskin_hasar == koyu_oran:
            morfoloji = "Hücresel Nekroz / Doku Çürümesi (Koyu Lezyon Odakları)"
            acil_eylem = "1. Kırmızı ile işaretli nekrotik dokuları steril aletle budayın.\n2. Sulamayı durdurun; kök boğazı drenajını kontrol edin."
        elif baskin_hasar == unsu_oran:
            morfoloji = "Yüzeyel Miselyum / Unsu Mantar Tabakası"
            acil_eylem = "1. Yaprak yüzeyini karbonatlı/hafif sabunlu pamukla silin.\n2. Bitkiyi havadar bir ortama alın, yaprak ıslatmaktan kaçının."
