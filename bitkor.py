# Çok Modlu (Multimodal) Bayesyen Karar Motoru ve Aktüatör Simülasyonu
def multimodal_decision_engine(image_probs, temperature, humidity):
    """
    Görüntü olasılıkları ile sıcaklık ve nem verilerini birleştiren karar motoru.
    image_probs: [Healthy, Early_Blight, Late_Blight] olasılık dizisi
    """
    # Sınıf indeksleri
    HEALTHY_IDX, EARLY_IDX, LATE_IDX = 0, 1, 2

    # Çevre katsayıları ağırlığı (Bayesyen Öncül Bilgi Güncelleme)
    # Erken ve Geç yanıklık (Mantar hastalıkları) yüksek nem ve 20-28°C arası sıcaklıkta çoğalır.
    fungal_risk_factor = 1.0
    if humidity > 80.0 and (20.0 <= temperature <= 28.0):
        fungal_risk_factor = 1.5
    else:
        fungal_risk_factor = 0.7

    # Skorları güncelleme
    updated_probs = np.array(image_probs, dtype=np.float64)
    updated_probs[EARLY_IDX] *= fungal_risk_factor
    updated_probs[LATE_IDX] *= fungal_risk_factor

    # Normalizasyon (Olasılıkların toplamını 1 yapma)
    updated_probs /= np.sum(updated_probs)

    best_class_idx = np.argmax(updated_probs)
    final_confidence = updated_probs[best_class_idx]

    # Aktüatör (İlaçlama Valfi) Tetikleme Kararı
    actuator_trigger = False
    if best_class_idx != HEALTHY_IDX and final_confidence >= 0.80:
        actuator_trigger = True

    return CLASSES[best_class_idx], final_confidence, actuator_trigger

